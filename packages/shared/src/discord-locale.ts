export function discordText(
  key: keyof Omit<
    typeof th,
    "statuses" | "errors" | "supportActions" | "categories"
  >,
  values: Record<string, string | number> = {},
) {
  return th[key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? "—"),
  );
}
export function discordStatus(status: string) {
  return th.statuses[status as keyof typeof th.statuses] || "รอตรวจสอบสถานะ";
}
export function discordError(code: string) {
  return th.errors[code as keyof typeof th.errors] || th.operationFailed;
}
